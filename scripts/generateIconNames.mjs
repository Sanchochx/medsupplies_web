// Generates the `IconName` union from the SVG files in src/assets/icons, so that using an icon that
// does not exist fails type checking. Run with `npm run icons:generate` after adding/removing icons.
import { readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const ICONS_DIR = fileURLToPath(new URL('../src/assets/icons/', import.meta.url));
const OUTPUT_FILE = fileURLToPath(new URL('../src/components/ui/iconNames.ts', import.meta.url));

const names = (await readdir(ICONS_DIR))
  .filter((file) => file.endsWith('.svg'))
  .map((file) => file.slice(0, -'.svg'.length))
  .sort();

const source = `// AUTO-GENERATED by scripts/generateIconNames.mjs from src/assets/icons/*.svg — do not edit.
// Run \`npm run icons:generate\` after adding or removing an icon.

export const ICON_NAMES = [
${names.map((name) => `  '${name}',`).join('\n')}
] as const;

export type IconName = (typeof ICON_NAMES)[number];
`;

await writeFile(OUTPUT_FILE, source);
process.stdout.write(`Generated ${names.length} icon names -> ${OUTPUT_FILE}\n`);
